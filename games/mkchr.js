/* the pictures: 8 x 8 */
const TILES = {
    0x01: ['########', '########', '########', '########', '########', '########', '########', '########'],   // white
    0x02: ['oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo'],   // green
    0x03: ['xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx', 'xxxxxxxx'],   // red
    0x04: ['..xxxx..', '.xxxxxx.', 'xx#xxxxx', 'x#xxxxxx', 'xxxxxxxx', 'xxxxxxxx', '.xxxxxx.', '..xxxx..'],   // a ball
    0x05: ['.oooooo.', 'oooooooo', 'o#.oo#.o', 'o..oo..o', 'oooooooo', 'oooooooo', 'oooooooo', '.oooooo.'],   // the snake's head
    0x06: ['....o...', '...o....', '.xx.xx..', 'xxxxxxx.', 'xx#xxxx.', 'xxxxxxx.', '.xxxxx..', '..x.x...'],   // an apple
    0x07: ['########', '#......#', '#.####.#', '#.#..#.#', '#.#..#.#', '#.####.#', '#......#', '########'],   // the wall
    0x08: ['.oooooo.', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', 'oooooooo', '.oooooo.'],   // the snake's body
    0x09: ['........', '........', '..####..', '..####..', '..####..', '..####..', '........', '........'],   // a dot of the frame
    0x0a: ['........', '.oooooo.', '.oooooo.', '.oooooo.', '.oooooo.', '.oooooo.', '.oooooo.', '........'],   // a light, on
};

const PIXEL = { '.': 0, '#': 1, o: 2, x: 3 };

function tile(rows) {
    const out = Buffer.alloc(16);
    rows.forEach((row, y) => {
        for (let x = 0; x < 8; x++) {
            const c = PIXEL[row[x]];
            if (c === undefined) throw new Error('a pixel "' + row[x] + '" in ' + rows.join(' '));
            if (c & 1) out[y] |= 0x80 >> x;
            if (c & 2) out[8 + y] |= 0x80 >> x;
        }
    });
    return out;
}

function build() {
    const chr = Buffer.alloc(8192);
    Object.keys(TILES).forEach((n) => {
        const rows = TILES[n];
        if (rows.length !== 8 || rows.some((r) => r.length !== 8)) throw new Error('tile ' + n + ' is not 8 x 8');
        tile(rows).copy(chr, n * 16);
    });
    Object.keys(FONT).forEach((ch) => {
        const rows = FONT[ch], n = ch.charCodeAt(0);
        if (n < 0x20 || n > 0x5f || rows.length !== 7 || rows.some((r) => r.length !== 5)) throw new Error('letter ' + ch + ' is not 5 x 7, or has no tile');
        tile(rows.map((r) => '.' + r + '..').concat(['........'])).copy(chr, n * 16);
    });
    return chr;
}

if (require.main === module) {
    if (!process.argv[2]) { console.error('usage: node mkchr.js <out.chr>'); process.exit(1); }
    fs.writeFileSync(process.argv[2], build());
}
module.exports = { build };
